// Convertit un code pays ISO 3166-1 alpha-2 (ex: "JP") en emoji drapeau.
function codeToFlag(code) {
  return code
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}

